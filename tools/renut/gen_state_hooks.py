#!/usr/bin/env python3
"""Writes the render and sampler state hook lines of reNut's hooks/state.cpp at Oblivion's addresses
(docs/renut-port.md, milestone 2).

Oblivion's D3D_InitializeApiState (sub_82569C30) copies 97 render-state records {getter, setter, default} from
0x82A5FA38 and 20 sampler-state records from 0x82A5FEC8 into the device; the game calls the state functions through
those copies. The order is XDK 2135's (zuma-nx, docs/zuma-notes.md "The states"): against N&B's order (the template
index of reNut's hooks) render states 0-56 are the same, Oblivion's 57 is a state N&B lacks (sub_82562838 keeps the
value in four device words), N&B's 57-95 are Oblivion's 58-96, N&B's 96-100 do not exist; the samplers are in the
same order. Template: zuma-nx's state.cpp lines (N&B index and name). Render states 0-9 (one shared stub setter
0x826756A8) and functions shared by several entries (the getter 0x823A29C8 of 0-9 and of Wrap10-15) stay unhooked.

  python tools/renut/gen_state_hooks.py [--zuma <zuma-nx state.cpp>] [--out out/renut/state_hooks.inc]
"""
import argparse
import collections
import os
import re
import struct

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
BASE = 0x82000000
RENDER_TABLE, RENDER_N = 0x82A5FA38, 97
SAMPLER_TABLE, SAMPLER_N = 0x82A5FEC8, 20
EXTRA = 57
LINE = re.compile(r'(?://.*?: )?BANJO_RENUT_HOOK\(sub_\w+, ([SG]et)(Render|Sampler)StateHook<(\d+)>\);\s*//\s*(\S+)')


def table(img, addr, n):
    w = struct.unpack_from('>%dI' % (3 * n), img, addr - BASE)
    return [(w[3 * i], w[3 * i + 1], w[3 * i + 2]) for i in range(n)]


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--zuma', default=os.path.join(ROOT, 'out', 'ref', 'zuma-nx', 'app', 'src', 'renut_engine', 'gpu',
                                                   'd3d', 'hooks', 'state.cpp'))
    ap.add_argument('--image', default=os.path.join(ROOT, 'tools', 'image.bin'))
    ap.add_argument('--out', default=os.path.join(ROOT, 'out', 'renut', 'state_hooks.inc'))
    a = ap.parse_args()
    img = open(a.image, 'rb').read()
    rs, ss = table(img, RENDER_TABLE, RENDER_N), table(img, SAMPLER_TABLE, SAMPLER_N)
    uses = collections.Counter(e[k] for t in (rs, ss) for e in t for k in (0, 1))

    names = {}
    for line in open(a.zuma, encoding='utf-8'):
        m = LINE.search(line)
        if m:
            names[(m.group(1), m.group(2), int(m.group(3)))] = m.group(4)

    out = ['// oblivion: generated by tools/renut/gen_state_hooks.py from the game\'s state tables (render 0x82A5FA38,',
           '// sampler 0x82A5FEC8) and zuma-nx\'s (XDK 2135) order; the template index is N&B\'s.']
    hooked = 0
    for kind, tab, n_nb in (('Render', rs, 101), ('Sampler', ss, 20)):
        for verb, field in (('Set', 1), ('Get', 0)):
            for nb in range(n_nb):
                name = names.get((verb, kind, nb), f'D3DDevice_{verb}{kind}State_{nb}')
                if kind == 'Render':
                    if nb < 10:
                        continue
                    idx = nb if nb < EXTRA else nb + 1
                else:
                    idx = nb
                hook = f'{verb}{kind}StateHook<{nb}>'
                if idx >= len(tab):
                    out.append(f'// oblivion: not in XDK 2417: BANJO_RENUT_HOOK(sub_XXXXXXXX, {hook});  // {name}')
                    continue
                addr = tab[idx][field]
                if uses[addr] > 1:
                    out.append(f'// oblivion: shared by {uses[addr]} table entries, left alone: '
                               f'BANJO_RENUT_HOOK(sub_{addr:08X}, {hook});  // {name}')
                    continue
                out.append(f'BANJO_RENUT_HOOK(sub_{addr:08X}, {hook});  // {name}  // oblivion: table entry {idx}')
                hooked += 1
                if kind == 'Render' and nb == EXTRA - 1:
                    e = tab[EXTRA]
                    func = 'OblivionSetRenderState57' if verb == 'Set' else 'OblivionGetRenderState57'
                    out.append(f'BANJO_RENUT_HOOK(sub_{e[field]:08X}, {func});  // XDK 2135/2417 render state 57 '
                               f'({verb.lower()}ter)  // oblivion: table entry 57')
                    hooked += 1
    with open(a.out, 'w', newline='\n') as f:
        f.write('\n'.join(out) + '\n')
    print(f'{hooked} state hooks -> {a.out}')


if __name__ == '__main__':
    main()
