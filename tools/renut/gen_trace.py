#!/usr/bin/env python3
"""Writes src/renut/d3d_trace_list.inc for the D3D call trace (src/renut/d3d_trace.cpp): every library function
called from game code (out/renut/d3d_api.txt, tools/renut/d3d_lib.py) and every setter of the device's render and
sampler state tables (called through the tables the device holds), one TRACE_FN(address, "kind") line each.

  python tools/renut/gen_trace.py
"""
import os
import re
import struct

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
BASE = 0x82000000
RENDER_TABLE, RENDER_N = 0x82A5FA38, 97
SAMPLER_TABLE, SAMPLER_N = 0x82A5FEC8, 20
LIB = (0x82550000, 0x82570000)


def main():
    img = open(os.path.join(ROOT, 'tools', 'image.bin'), 'rb').read()
    entries = {}
    for line in open(os.path.join(ROOT, 'out', 'renut', 'd3d_api.txt')):
        m = re.match(r'sub_([0-9A-F]{8})', line)
        entries[int(m.group(1), 16)] = 'api'
    for table, n, kind in ((RENDER_TABLE, RENDER_N, 'rs'), (SAMPLER_TABLE, SAMPLER_N, 'ss')):
        w = struct.unpack_from('>%dI' % (3 * n), img, table - BASE)
        for i in range(n):
            setter = w[3 * i + 1]
            if LIB[0] <= setter < LIB[1]:
                entries.setdefault(setter, f'{kind}{i}')
    out = os.path.join(ROOT, 'src', 'renut', 'd3d_trace_list.inc')
    with open(out, 'w') as f:
        f.write('// Generated by tools/renut/gen_trace.py: D3D functions wrapped by the call trace.\n')
        for a in sorted(entries):
            f.write(f'TRACE_FN({a:08X}, "{entries[a]}")\n')
    print(f'{len(entries)} functions -> {out}')


if __name__ == '__main__':
    main()
