#!/usr/bin/env python3
"""reOblivion web (2026-11-18): one of Renut's host shaders as WGSL for plume_webgpu.

    python tools/webgpu_host_shader.py --dxc dxc.exe --spirv-cross spirv-cross.exe --profile ps_6_0 --stem present_ps
        --src shaders/host/present_ps.hlsl --out host_shaders/present_ps.wgsl.h

DXC (SPIR-V, -DBANJO_DEKO3D: the flavour without buffer addresses; D3D clip space, no -fvk-invert-y), SPIRV-Cross
(Vulkan GLSL 4.60), tools/webgpu_glsl.py, then glslang and tint in the reoblivion-tint container (web/tint/Dockerfile).
The header holds g_<stem>_wgsl: "WGS1", stage (0 vertex, 4 fragment, 5 compute), the binding line's size, the WGSL's
size, then both (plume_webgpu's WebGpuShaderBlob). Geometry shaders have no WebGPU stage: an empty blob (the renderer
then draws without them, as on a device without geometry shaders).
"""
import argparse
import os
import struct
import subprocess
import sys
import tempfile

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import webgpu_glsl  # noqa: E402

STAGES = {'vs': ('vert', 0), 'ps': ('frag', 4), 'cs': ('comp', 5), 'gs': ('geom', 3)}
IMAGE = 'reoblivion-tint'


def write_header(path, stem, src, blob, note):
    lines = [f'// Generated by tools/webgpu_host_shader.py from {os.path.basename(src)}: {note}.',
             '#pragma once', '#include <cstdint>', f'static const uint8_t g_{stem}_wgsl[] = {{']
    for i in range(0, len(blob), 24):
        lines.append('    ' + ', '.join(f'0x{b:02X}' for b in blob[i:i + 24]) + ',')
    if not blob:
        lines.append('    0')
    lines.append('};')
    os.makedirs(os.path.dirname(os.path.abspath(path)), exist_ok=True)
    with open(path + '.tmp', 'w', encoding='utf-8', newline='\n') as f:
        f.write('\n'.join(lines) + '\n')
    os.replace(path + '.tmp', path)


def main():
    ap = argparse.ArgumentParser()
    for k in ('dxc', 'spirv-cross', 'profile', 'stem', 'src', 'out'):
        ap.add_argument('--' + k, required=True)
    ap.add_argument('--optional', action='store_true',
                    help='a shader the renderer can do without: an empty blob, with the reason, when it does not convert')
    a = ap.parse_args()
    a.dxc, a.spirv_cross, a.src = (os.path.abspath(p) for p in (a.dxc, a.spirv_cross, a.src))
    kind = a.profile[:2]
    if kind not in STAGES:
        sys.exit(f'webgpu_host_shader: profile {a.profile}')
    stage_name, stage = STAGES[kind]
    if kind == 'gs':
        write_header(a.out, a.stem, a.src, b'', 'none (WebGPU has no geometry stage)')
        return 0
    with tempfile.TemporaryDirectory() as tmp:
        spv = os.path.join(tmp, 'in.spv')
        vk = os.path.join(tmp, 'in.vk.glsl')
        r = subprocess.run([a.dxc, '-T', a.profile, '-E', 'main', '-HV', '2021', '-all-resources-bound',
                            '-Wno-ignored-attributes', '-spirv', '-fvk-use-dx-layout', '-DBANJO_DEKO3D', '-DRENUT_WEBGPU',
                            a.src, '-Fo', spv], capture_output=True, text=True)
        if r.returncode != 0:
            sys.exit(f'webgpu_host_shader: DXC failed for {a.src}:\n{r.stdout}{r.stderr}')
        r = subprocess.run([a.spirv_cross, spv, '--version', '460', '--vulkan-semantics', '--relax-nan-checks',
                            '--output', vk], capture_output=True, text=True)
        if r.returncode != 0:
            sys.exit(f'webgpu_host_shader: SPIRV-Cross failed for {a.src}:\n{r.stdout}{r.stderr}')
        try:
            glsl, meta = webgpu_glsl.convert(open(vk, encoding='utf-8').read(), stage_name)
        except webgpu_glsl.Unsupported as e:
            if a.optional:
                write_header(a.out, a.stem, a.src, b'', f'none ({e})')
                return 0
            sys.exit(f'webgpu_host_shader: {a.src}: {e}')
        with open(os.path.join(tmp, 'in.glsl'), 'w', encoding='utf-8', newline='\n') as f:
            f.write(glsl)
        work = tmp.replace('\\', '/')
        env = dict(os.environ, MSYS_NO_PATHCONV='1')
        r = subprocess.run(['docker', 'run', '--rm', '-v', f'{work}:/work', IMAGE, 'sh', '-c',
                            f'glslangValidator -V --target-env vulkan1.1 -S {stage_name} -o in.spv in.glsl && '
                            'tint --format wgsl --allow-non-uniform-derivatives true -o out.wgsl in.spv'],
                           capture_output=True, text=True, env=env)
        if r.returncode != 0:
            sys.exit(f'webgpu_host_shader: glslang/tint failed for {a.src} ({os.path.join(tmp, "in.glsl")}):\n'
                     f'{r.stdout}{r.stderr}')
        wgsl = open(os.path.join(tmp, 'out.wgsl'), 'rb').read()
    m = meta.encode()
    blob = b'WGS1' + struct.pack('<III', stage, len(m), len(wgsl)) + m + wgsl
    write_header(a.out, a.stem, a.src, blob, f'{len(wgsl)} bytes of WGSL; {meta}')
    return 0


if __name__ == '__main__':
    sys.exit(main())
